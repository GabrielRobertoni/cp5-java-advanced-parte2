-- =====================================================================
-- V1 - Criação das tabelas do Mercado Express (PostgreSQL)
-- Observação: no PostgreSQL, nomes sem aspas são gravados em minúsculas
-- (TDS_Sec_MVC_TB_Mercado -> tds_sec_mvc_tb_mercado).
-- =====================================================================

-- Usuários do sistema (perfil de acesso: ADMIN ou CLIENTE)
CREATE TABLE TDS_Users_Mercado (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(100) NOT NULL,
    email      VARCHAR(150) NOT NULL,
    senha      VARCHAR(100) NOT NULL,          -- hash BCrypt (nunca a senha pura)
    perfil     VARCHAR(20)  NOT NULL,
    criado_em  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_users_mercado_email UNIQUE (email),
    CONSTRAINT ck_users_mercado_perfil CHECK (perfil IN ('ADMIN', 'CLIENTE'))
);

-- Produtos do mercado
CREATE TABLE TDS_Sec_MVC_TB_Mercado (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome               VARCHAR(100)  NOT NULL,
    tipo               VARCHAR(50)   NOT NULL,
    setor              VARCHAR(50)   NOT NULL,
    tamanho            VARCHAR(30),
    preco              NUMERIC(10,2) NOT NULL,
    quantidade_estoque INTEGER       NOT NULL DEFAULT 0,
    descricao          VARCHAR(255),
    criado_em          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_mercado_preco CHECK (preco > 0),
    CONSTRAINT ck_mercado_estoque CHECK (quantidade_estoque >= 0)
);

CREATE INDEX idx_mercado_nome ON TDS_Sec_MVC_TB_Mercado (LOWER(nome));
CREATE INDEX idx_mercado_setor ON TDS_Sec_MVC_TB_Mercado (setor);
