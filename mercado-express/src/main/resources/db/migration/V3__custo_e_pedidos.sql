-- Pedidos (compras). O número do pedido é o próprio id.
CREATE TABLE TDS_Pedidos_Mercado (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id            BIGINT REFERENCES TDS_Users_Mercado (id) ON DELETE SET NULL,
    cliente_nome          VARCHAR(100)  NOT NULL,
    cliente_email         VARCHAR(150)  NOT NULL,
    canal                 VARCHAR(10)   NOT NULL,
    forma_pagamento       VARCHAR(20)   NOT NULL,
    status                VARCHAR(30)   NOT NULL,
    valor_total           NUMERIC(12,2) NOT NULL,
    custo_total           NUMERIC(12,2) NOT NULL,
    transacao_id          UUID          NOT NULL,
    codigo_autorizacao    VARCHAR(30),
    motivo_recusa         VARCHAR(255),
    criado_em             TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    pagamento_enviado_em  TIMESTAMP,
    respondido_em         TIMESTAMP,
    email_status          VARCHAR(20)   NOT NULL DEFAULT 'NAO_APLICAVEL',
    email_solicitacao_id  UUID,
    email_id              UUID,
    email_solicitado_em   TIMESTAMP,
    email_atualizado_em   TIMESTAMP,
    email_erro            VARCHAR(500),
    CONSTRAINT uk_pedidos_transacao UNIQUE (transacao_id),
    CONSTRAINT ck_pedidos_canal CHECK (canal IN ('WEB', 'API')),
    CONSTRAINT ck_pedidos_forma CHECK (forma_pagamento IN ('PIX', 'CARTAO_CREDITO', 'CARTAO_DEBITO')),
    CONSTRAINT ck_pedidos_status CHECK (status IN ('AGUARDANDO_PAGAMENTO', 'PAGO', 'RECUSADO')),
    CONSTRAINT ck_pedidos_email CHECK (email_status IN ('NAO_APLICAVEL', 'PENDENTE', 'SOLICITADO', 'ENVIADO', 'ERRO')),
    CONSTRAINT ck_pedidos_valor CHECK (valor_total > 0),
    CONSTRAINT ck_pedidos_custo CHECK (custo_total >= 0)
);

CREATE INDEX idx_pedidos_status ON TDS_Pedidos_Mercado (status);
CREATE INDEX idx_pedidos_usuario ON TDS_Pedidos_Mercado (usuario_id);
CREATE INDEX idx_pedidos_respondido ON TDS_Pedidos_Mercado (respondido_em);

-- Itens do pedido: guardam nome, setor, preço e custo da época da compra
CREATE TABLE TDS_Itens_Pedido_Mercado (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id       BIGINT        NOT NULL REFERENCES TDS_Pedidos_Mercado (id) ON DELETE CASCADE,
    produto_id      BIGINT        REFERENCES TDS_Sec_MVC_TB_Mercado (id) ON DELETE SET NULL,
    produto_nome    VARCHAR(100)  NOT NULL,
    produto_setor   VARCHAR(50)   NOT NULL,
    quantidade      INTEGER       NOT NULL,
    preco_unitario  NUMERIC(10,2) NOT NULL,
    custo_unitario  NUMERIC(10,2) NOT NULL,
    subtotal        NUMERIC(12,2) NOT NULL,
    CONSTRAINT ck_itens_quantidade CHECK (quantidade > 0)
);

CREATE INDEX idx_itens_pedido ON TDS_Itens_Pedido_Mercado (pedido_id);
CREATE INDEX idx_itens_produto ON TDS_Itens_Pedido_Mercado (produto_id);
